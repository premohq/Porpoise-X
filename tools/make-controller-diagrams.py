#!/usr/bin/env python3
"""Porpoise - the Controller Hub's controller pictures, from Ruben's diagrams.

    python3 tools/make-controller-diagrams.py

tools/controller-diagrams/art.json holds Ruben's controller diagrams (the
DualSense, the PlayStation Move, the Move Navigation controller, the Wii
Remote, the PS3 Eye) as paths: the outline ("lines"), the body's shape, and
where each control sits ("anchors"). This draws each one white on clear (the
app tints it) into assets/ui/diagrams/<kind>.png, and writes
src/ui_ctl_diagrams.inc: each picture's view box, its controls' places, and
how big each control is, across and down (so a label's line stops at its edge).
"""
import io
import json
import re
import sys
from pathlib import Path

import cairosvg
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / "tools" / "controller-diagrams" / "art.json"
OUT = ROOT / "assets" / "ui" / "diagrams"
INC = ROOT / "src" / "ui_ctl_diagrams.inc"
# The long side in pixels: big enough for the hub's largest picture.
LONG = {"dualsense": 820, "move": 820, "movenav": 720, "remote": 720, "eye": 300}
# Drawn now (the Navigation and the Wii Remote wait for their controllers: their places are written all the same).
DRAWN = {"dualsense", "move", "eye"}
ORDER = ["dualsense", "move", "movenav", "remote", "eye"]


def bbox(d):
    nums = re.findall(r"[MLQCAZmlqcazhvHV]|-?\d*\.?\d+(?:e-?\d+)?", d)
    # Absolute commands only matter for a rough size; relative arcs (circ) are handled by the caller.
    xs, ys, cmd, vals = [], [], None, []
    for t in nums:
        if re.match(r"[A-Za-z]", t):
            cmd = t
            continue
        vals.append(float(t))
    pts = list(zip(vals[0::2], vals[1::2]))
    xs = [p[0] for p in pts]
    ys = [p[1] for p in pts]
    return min(xs), min(ys), max(xs), max(ys)


def size_of(d, vb):
    """Half the control's size: its path drawn alone, measured."""
    x, y, w, h = vb
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{x} {y} {w} {h}" width="{w}" height="{h}">'
           f'<path d="{d}" fill="#fff"/></svg>')
    im = Image.open(io.BytesIO(cairosvg.svg2png(bytestring=svg.encode()))).convert("RGBA")
    box = im.split()[3].getbbox()
    if not box:
        return 0.0, 0.0
    return (box[2] - box[0]) / 2, (box[3] - box[1]) / 2


def svg_of(k, v):
    x, y, w, h = v["vb"]
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{x} {y} {w} {h}">',
             '<defs><linearGradient id="b" x1="0" y1="0" x2="0" y2="1">'
             '<stop offset="0" stop-color="#fff" stop-opacity="0.16"/>'
             '<stop offset="1" stop-color="#fff" stop-opacity="0.05"/></linearGradient></defs>',
             f'<path d="{v["body"]}" fill="url(#b)"/>']
    for d in v["lines"]:
        parts.append(f'<path d="{d}" fill="#fff"/>')
    parts.append("</svg>")
    return "".join(parts)


def main() -> int:
    art = json.loads(ART.read_text(encoding="utf-8"))
    OUT.mkdir(parents=True, exist_ok=True)
    inc = ["/* Generated by tools/make-controller-diagrams.py from Ruben's controller diagrams",
           " * (tools/controller-diagrams/art.json): each picture's view box, and its",
           " * controls: where (view box units) and how big (half across, half down). */"]
    for k in ORDER:
        v = art[k]
        x, y, w, h = v["vb"]
        scale = LONG[k] / max(w, h)
        if k not in DRAWN:
            (OUT / f"{k}.png").unlink(missing_ok=True)
            inc.append(f'{{"{k}", {{{x}, {y}, {w}, {h}}}, {{')
            for name, (ax, ay) in v["anchors"].items():
                rx, ry = size_of(v["discs"][name], v["vb"]) if name in v["discs"] else (0.0, 0.0)
                inc.append(f'    {{"{name}", {ax}, {ay}, {rx:.1f}f, {ry:.1f}f}},')
            inc.append("}},")
            continue
        png = cairosvg.svg2png(bytestring=svg_of(k, v).encode(), output_width=round(w * scale),
                               output_height=round(h * scale))
        im = Image.open(io.BytesIO(png)).convert("RGBA")
        a = im.split()[3].point(lambda p: (p + 8) // 17 * 17)  # (16 levels: smaller, the same to the eye)
        la = Image.merge("LA", (Image.new("L", im.size, 255), a))
        path = OUT / f"{k}.png"
        la.save(path, optimize=True)
        try:
            import oxipng
            oxipng.optimize(str(path), level=6, strip=oxipng.StripChunks.all())
        except ImportError:
            pass
        print(f"{path.relative_to(ROOT)}: {im.width} x {im.height}, {path.stat().st_size} bytes")
        inc.append(f'{{"{k}", {{{x}, {y}, {w}, {h}}}, {{')
        for name, (ax, ay) in v["anchors"].items():
            rx, ry = size_of(v["discs"][name], v["vb"]) if name in v["discs"] else (0.0, 0.0)
            inc.append(f'    {{"{name}", {ax}, {ay}, {rx:.1f}f, {ry:.1f}f}},')
        inc.append("}},")
    INC.write_text("\n".join(inc) + "\n", encoding="utf-8")
    print(f"{INC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
